#!/usr/bin/env bash
# Keeps wiki/ current: regenerates wiki/files.md and lists pages whose sources changed since the page was last committed.
# Usage: bash wiki/update.sh [--check]   (--check only reports, writes nothing)
cd "$(git rev-parse --show-toplevel 2>/dev/null)" || exit 0

if [ "$1" != "--check" ]; then
  tmp=$(mktemp)
  {
    echo "# Files (generated by wiki/update.sh, don't edit)"
    echo
    echo "| File | First heading |"
    echo "|---|---|"
    git ls-files -- '*.md' '*.ino' '*.py' '*.cir' '*.csv' ':!wiki/' ':!uploads/' | while read -r f; do
      h=$(grep -m1 -E '^(#|//|;|\*) ?' "$f" | sed -E 's/^(#+|\/\/|;|\*) ?//; s/\|/\\|/g' | cut -c1-90)
      echo "| [$f](../$f) | $h |"
    done
  } > "$tmp"
  cmp -s "$tmp" wiki/files.md || mv "$tmp" wiki/files.md
  rm -f "$tmp"
fi

stale=""
for page in wiki/*.md; do
  src=$(sed -n '1s/^<!-- sources: \(.*\) -->$/\1/p' "$page")
  [ -z "$src" ] && continue
  page_t=$(git log -1 --format=%ct -- "$page")
  [ -z "$page_t" ] && continue  # page not committed yet
  # shellcheck disable=SC2086
  src_t=$(git log -1 --format=%ct -- $src ':!wiki/')
  [ -n "$src_t" ] && [ "$src_t" -gt "$page_t" ] && stale="$stale $page"
done

if [ -n "$stale" ]; then
  echo "WIKI STALE: these pages' sources changed after the page was last updated:$stale"
  echo "Before answering project questions, re-read their sources (first line of each page) and update the pages, then commit."
fi
exit 0
